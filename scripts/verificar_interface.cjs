// Verificação da experiência principal. Requer Playwright e o app em 127.0.0.1:8501.
const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const appUrl = process.env.APP_URL || 'http://127.0.0.1:8501';
const output = path.join(root, '.build', 'ui');
fs.mkdirSync(output, { recursive: true });
(async () => {
  const browser = await chromium.launch({ headless: true });
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1100 } });
    const errors = [];
    page.on('pageerror', error => errors.push(String(error)));
    await page.goto(appUrl);
    await page.waitForFunction(() => !document.querySelector('#predict').disabled);
    assert.equal(await page.locator('#primary-fields').isVisible(), false, 'Campos técnicos devem começar recolhidos');
    await page.screenshot({ path: path.join(output, 'desktop-inicio.png'), fullPage: true });
    const analyze = async () => {
      await page.locator('#predict').click();
      await page.locator('#result .decision').waitFor();
      await page.waitForFunction(() => !document.querySelector('#predict').disabled);
    };
    await analyze();
    assert.match(await page.locator('#result').innerText(), /Sem alerta nesta análise/);
    assert.match(await page.locator('.truth-card').innerText(), /acertou/);
    await page.locator('[data-kind="fraude"]').click();
    assert.equal(await page.locator('#result-details').isVisible(), false, 'Trocar exemplo deve limpar resultado antigo');
    await analyze();
    assert.match(await page.locator('#result').innerText(), /segunda análise/);
    assert.match(await page.locator('.truth-card').innerText(), /acertou/);
    assert.equal(await page.locator('#trees i').count(), 100);
    await page.screenshot({ path: path.join(output, 'desktop-resultado.png'), fullPage: true });
    await page.locator('[data-kind="erros"]').click();
    await analyze();
    assert.match(await page.locator('.truth-card').innerText(), /falso negativo/);
    await page.locator('#next-example').click();
    await analyze();
    assert.match(await page.locator('.truth-card').innerText(), /falso negativo/);
    await page.locator('#next-example').click();
    await analyze();
    assert.match(await page.locator('.truth-card').innerText(), /falso positivo/);
    await page.locator('.sensitivity summary').click();
    await page.locator('#threshold').fill('90');
    assert.equal(await page.locator('#result-details').isVisible(), false);
    await analyze();
    assert.match(await page.locator('.truth-card').innerText(), /acertou/);
    await page.locator('#reset-threshold').click();
    await page.locator('#edit-details > summary').click();
    await page.locator('#f-Amount').fill('500');
    await analyze();
    assert.match(await page.locator('.truth-card').innerText(), /não tem gabarito/);
    await page.locator('#f-Amount').fill('-1');
    await page.locator('#predict').click();
    assert.match(await page.locator('#error').innerText(), /Amount/);
    await page.locator('#restore-example').click();
    assert.equal(await page.locator('#error').isVisible(), false);
    await page.locator('[data-mode="csv"]').click();
    await page.locator('#predict').click();
    assert.match(await page.locator('#error').innerText(), /Escolha um arquivo/);
    await page.locator('#csv').setInputFiles(path.join(root, 'demo', 'demo_final.csv'));
    await analyze();
    assert.match(await page.locator('#result-badge').innerText(), /10 transações/);
    assert.equal(await page.locator('#batch-results tbody tr').count(), 10);
    assert.match(await page.locator('.truth-card').innerText(), /não tem gabarito/);
    const downloadEvent = page.waitForEvent('download');
    await page.locator('#download-results').click();
    const download = await downloadEvent;
    const downloadPath = path.join(output, 'analise.csv');
    await download.saveAs(downloadPath);
    const csv = fs.readFileSync(downloadPath, 'utf8').trim().split('\n');
    assert.equal(csv.length, 11);
    assert.equal(csv[0], 'linha,score_fraude,classe_prevista,decisao');
    await page.locator('#csv').setInputFiles({ name: 'invalido.csv', mimeType: 'text/csv', buffer: Buffer.from('Time,Amount\n1,2') });
    await page.locator('#predict').click();
    await page.locator('#error').waitFor();
    assert.match(await page.locator('#error').innerText(), /Ausentes/);
    await page.locator('[data-tab="como"]').click();
    assert.equal(await page.locator('#como').isVisible(), true);
    await page.locator('#try-errors').click();
    assert.equal(await page.locator('#example-input').isVisible(), true);
    assert.equal(await page.locator('[data-kind="erros"]').getAttribute('aria-pressed'), 'true');
    await page.locator('[data-tab="evidencias"]').click();
    assert.equal(await page.locator('#found-frauds').innerText(), '68 de 95');
    assert.equal(await page.locator('#simple-comparison tbody tr').count(), 3);
    await page.locator('.technical > summary').click();
    assert.equal(await page.locator('#experiments tbody tr').count(), 4);
    assert.equal(await page.locator('#test-metrics tbody tr').count(), 3);
    assert.equal(await page.locator('#errors tbody tr').count(), 4);
    await page.screenshot({ path: path.join(output, 'desktop-evidencias.png'), fullPage: true });
    // Uma resposta atrasada não pode preencher a tela depois de uma mudança de exemplo.
    await page.locator('[data-tab="analisar"]').click();
    let releaseResponse;
    const holdResponse = new Promise(resolve => { releaseResponse = resolve; });
    await page.route('**/api/predict', async route => { const response = await route.fetch(); await holdResponse; await route.fulfill({ response }).catch(() => {}); });
    const started = page.waitForRequest('**/api/predict');
    await page.locator('#predict').click();
    await started;
    await page.locator('[data-kind="normal"]').click();
    releaseResponse();
    await page.unrouteAll({ behavior: 'wait' });
    assert.equal(await page.locator('#result-details').isVisible(), false, 'Resposta antiga deve ser descartada');
    for (const width of [390, 760, 1024]) {
      await page.setViewportSize({ width, height: 844 });
      for (const tab of ['analisar', 'como', 'evidencias']) {
        await page.locator(`[data-tab="${tab}"]`).click();
        assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, `Rolagem horizontal em ${width}px: ${tab}`);
      }
    }
    await page.setViewportSize({ width: 390, height: 844 });
    await page.locator('[data-tab="analisar"]').click();
    await page.screenshot({ path: path.join(output, 'mobile-inicio.png'), fullPage: true });
    await analyze();
    await page.screenshot({ path: path.join(output, 'mobile-resultado.png'), fullPage: true });
    assert.equal(errors.length, 0, errors.join('\n'));
    console.log('OK: exemplos, acertos e erros, corte, edição, CSV, download, respostas antigas e telas de 390/760/1024/1440px.');
    console.log('Capturas em .build/ui/.');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
